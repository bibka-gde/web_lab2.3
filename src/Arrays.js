/*
  В функцию arraySorting() приходит строка чисел с разделительными запятыми вида "1,2,33,0,17".
  Преобразуйте строку в массив чисел, отсортируйте их по возрастанию и верните строку с упорядоченными числами,
  разделенными запятыми.
*/
export function arraySorting(data) {
    // 1. Разбиваем строку на массив строк по запятой
    // 2. Преобразуем каждую строку в число (Number)
    // 3. Сортируем числа по возрастанию (a - b)
    // 4. Собираем обратно в строку через запятую
    return data
        .split(',')
        .map(Number)
        .sort((a, b) => a - b)
        .join(',');
}

/*
  В функцию arrayFiltering() приходит массив целых чисел.
  Преобразуйте массив таким образом, чтобы все элементы массива, в которых содержатся числа более 100,
  были бы удалены из массива, и верните его в качестве результата функции.
*/
export function arrayFiltering(data) {
    // Оставляем в массиве только те числа, которые меньше или равны 100
    return data.filter((num) => num <= 100);
}

/*
  В функцию arrayPushing() приходят два массива целых чисел размерностью 5 элементов.
  Получите третий массив размерностью 10 элементов, в котором последовательно чередуются
  значения из первых двух массивов, и верните его в качестве результата функции.
*/
export function arrayPushing(array1, array2) {
    const result = [];

    // Проходим по массивам (они гарантированно по 5 элементов)
    for (let i = 0; i < array1.length; i++) {
        result.push(array1[i]); // Добавляем элемент из первого массива
        result.push(array2[i]); // Сразу за ним добавляем элемент из второго
    }

    return result;
}
